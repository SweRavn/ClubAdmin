// People (docs/domain-model.md): a person exists once in the system and has no
// email. Personal identity numbers are stored encrypted with a blind index for
// duplicate matching; protected persons never have an address stored.

import { getCountryPack, isSupportedCountry } from "@clubadmin/country-packs";
import { audit, type Database, outbox, type Tx } from "@clubadmin/db";
import {
  type CreatePersonInput,
  CreatePersonSchema,
  type SignUpPersonInput,
  SignUpPersonSchema,
  type UpdatePersonInput,
  UpdatePersonSchema,
  uuidv7,
} from "@clubadmin/shared";

import type { FieldEncryption } from "../../platform/crypto/field-encryption.ts";
import { DomainError } from "../../platform/domain/domain-error.ts";
import {
  actorPersonId,
  type Context,
  definedOnly,
  parseInput,
  runAs,
} from "../../platform/domain/run.ts";
import * as repo from "./people.repository.ts";

export interface Person {
  id: string;
  givenName: string;
  familyName: string;
  birthDate: string | null;
  gender: string | null;
  protectedIdentity: boolean;
  phone: string | null;
  address: repo.PersonRow["address"];
  hasPersonalIdentityNumber: boolean;
  deceasedAt: Date | null;
  anonymizedAt: Date | null;
  mergedIntoPersonId: string | null;
  createdByPersonId: string | null;
}

const PIN_PURPOSE = "personal_identity_number";
const pinAad = (personId: string) => `people.personal_identity_number:${personId}`;

function toPerson(row: repo.PersonRow): Person {
  return {
    id: row.id,
    givenName: row.givenName,
    familyName: row.familyName,
    birthDate: row.birthDate,
    gender: row.gender,
    protectedIdentity: row.protectedIdentity,
    phone: row.phone,
    address: row.address,
    hasPersonalIdentityNumber: row.personalIdentityNumber !== null,
    deceasedAt: row.deceasedAt,
    anonymizedAt: row.anonymizedAt,
    mergedIntoPersonId: row.mergedIntoPersonId,
    createdByPersonId: row.createdByPersonId,
  };
}

export class PeopleService {
  private readonly db: Database;
  private readonly encryption: FieldEncryption;

  constructor(db: Database, encryption: FieldEncryption) {
    this.db = db;
    this.encryption = encryption;
  }

  /**
   * Sign-up: creates the acting person's own row (context.personId is the new
   * person's ID, generated by the sign-up flow). The account follows with
   * AccountsService.createAccount.
   */
  createSelf(context: Context, input: SignUpPersonInput): Promise<Person> {
    return runAs(this.db, context, (tx) => this.createSelfInTx(tx, context, input));
  }

  createSelfInTx(tx: Tx, context: Context, input: SignUpPersonInput): Promise<Person> {
    return this.createPersonInTx(tx, context, input, {
      id: actorPersonId(context),
      schema: SignUpPersonSchema,
    });
  }

  /** Creates a person without email (children, people added by a club). `id`: fixed (demo seed). */
  createPerson(
    context: Context,
    input: CreatePersonInput,
    options: { id?: string } = {},
  ): Promise<Person> {
    return runAs(this.db, context, (tx) =>
      this.createPersonInTx(tx, context, input, options.id ? { id: options.id } : {}),
    );
  }

  async createPersonInTx(
    tx: Tx,
    context: Context,
    input: CreatePersonInput | SignUpPersonInput,
    options: { id?: string; schema?: typeof SignUpPersonSchema } = {},
  ): Promise<Person> {
    const data = parseInput(options.schema ?? CreatePersonSchema, input);
    if (data.protectedIdentity && data.address) throw new DomainError("protected_address");
    const id = options.id ?? uuidv7();
    const pin = data.personalIdentityNumber
      ? await this.sealPersonalIdentityNumber(
          tx,
          id,
          data.personalIdentityNumber,
          data.birthDate ?? null,
        )
      : { personalIdentityNumber: null, personalIdentityNumberHash: null };
    await repo.insertPerson(tx, {
      id,
      givenName: data.givenName,
      familyName: data.familyName,
      birthDate: data.birthDate ?? null,
      gender: data.gender ?? null,
      phone: data.phone ?? null,
      address: data.address ?? null,
      protectedIdentity: data.protectedIdentity,
      ...pin,
      // Self sign-up creates the actor's own person; otherwise the actor created it.
      createdByPersonId: context.personId && context.personId !== id ? context.personId : null,
    });
    await audit.record(tx, {
      action: "person.created",
      resourceType: "person",
      resourceId: id,
      changedFields: Object.keys(data).filter((k) => data[k as keyof typeof data] != null),
    });
    const row = await repo.findPerson(tx, id);
    if (!row) throw new DomainError("not_found");
    return toPerson(row);
  }

  getPerson(context: Context, personId: string): Promise<Person> {
    return runAs(this.db, context, (tx) => this.getPersonInTx(tx, personId));
  }

  async getPersonInTx(tx: Tx, personId: string): Promise<Person> {
    const row = await repo.findPerson(tx, personId);
    if (!row) throw new DomainError("not_found");
    return toPerson(row);
  }

  /** People by ID, as visible to the transaction (rows the actor may not reach are missing). */
  getPeople(context: Context, personIds: readonly string[]): Promise<Person[]> {
    return runAs(this.db, context, async (tx) =>
      (await repo.findPeople(tx, personIds)).map(toPerson),
    );
  }

  /**
   * Names and global protected flags for the person presenter, in the order
   * asked (missing rows left out). Never serialise these yourself: pass them
   * to PersonPresenter (ADR 0022).
   */
  summaries(context: Context, personIds: readonly string[]): Promise<repo.PersonSummaryRow[]> {
    return runAs(this.db, context, async (tx) => {
      const rows = new Map((await repo.findSummaries(tx, personIds)).map((r) => [r.id, r]));
      return personIds.flatMap((id) => {
        const row = rows.get(id);
        return row ? [row] : [];
      });
    });
  }

  /** Access log: someone other than the person viewed a protected person's profile (ADR 0022). */
  recordProtectedView(context: Context, personId: string): Promise<void> {
    return runAs(this.db, context, (tx) =>
      audit.record(tx, {
        action: "person.protected.viewed",
        resourceType: "person",
        resourceId: personId,
      }),
    );
  }

  /** People by ID without an actor (DEV_AUTH persona picker only). */
  listForDevelopment(personIds: readonly string[]): Promise<Person[]> {
    return this.db.withSystem("dev:personas", {}, async (tx) =>
      (await repo.findPeople(tx, personIds)).map(toPerson),
    );
  }

  /** Marks a person as merged into another (or clears it on undo); person-merge module. */
  async setMergedIntoInTx(tx: Tx, personId: string, into: string | null): Promise<void> {
    await repo.updatePerson(tx, personId, { mergedIntoPersonId: into });
  }

  /** Decrypts the personal identity number (audited). Authorization comes with P0.7. */
  revealPersonalIdentityNumber(
    context: Context,
    personId: string,
  ): Promise<{ country: string; value: string } | null> {
    return runAs(this.db, context, async (tx) => {
      const row = await repo.findPerson(tx, personId);
      if (!row) throw new DomainError("not_found");
      if (!row.personalIdentityNumber) return null;
      await audit.record(tx, {
        action: "person.personal_identity_number.viewed",
        resourceType: "person",
        resourceId: personId,
      });
      const plain = await this.encryption.decrypt(tx, row.personalIdentityNumber, pinAad(personId));
      const separator = plain.indexOf(":");
      return { country: plain.slice(0, separator), value: plain.slice(separator + 1) };
    });
  }

  /** The blind index used to find people with the same personal identity number. */
  personalIdentityNumberHash(country: string, value: string): string | null {
    if (!isSupportedCountry(country)) return null;
    const normalized = getCountryPack(country).personalIdFormat.normalize(value);
    return normalized ? this.encryption.blindIndex(PIN_PURPOSE, `${country}:${normalized}`) : null;
  }

  updateProfile(context: Context, personId: string, patch: UpdatePersonInput): Promise<Person> {
    return runAs(this.db, context, async (tx) => {
      const data = parseInput(UpdatePersonSchema, patch);
      const current = await repo.lockPerson(tx, personId);
      if (!current) throw new DomainError("not_found");
      if (current.protectedIdentity && data.address) throw new DomainError("protected_address");

      const { personalIdentityNumber, ...plain } = data;
      const values: Partial<repo.NewPersonRow> = definedOnly(plain);
      if (personalIdentityNumber !== undefined) {
        Object.assign(
          values,
          personalIdentityNumber
            ? await this.sealPersonalIdentityNumber(
                tx,
                personId,
                personalIdentityNumber,
                data.birthDate ?? current.birthDate,
              )
            : { personalIdentityNumber: null, personalIdentityNumberHash: null },
        );
      }
      const changed = Object.keys(data);
      if (changed.length > 0) {
        await repo.updatePerson(tx, personId, values);
        await audit.record(tx, {
          action: "person.updated",
          resourceType: "person",
          resourceId: personId,
          changedFields: changed,
        });
      }
      return this.getPersonInTx(tx, personId);
    });
  }

  /**
   * Sets or clears the global protected identity flag (ADR 0022). Only the
   * person themselves or a parent/legal guardian may change it. Turning it on
   * removes the stored address.
   */
  setProtectedIdentity(context: Context, personId: string, value: boolean): Promise<Person> {
    return runAs(this.db, context, async (tx) => {
      const actor = actorPersonId(context);
      const current = await repo.lockPerson(tx, personId);
      if (!current) throw new DomainError("not_found");
      if (actor !== personId && !(await repo.actorIsFullGuardianOf(tx, personId))) {
        throw new DomainError("not_allowed");
      }
      if (current.protectedIdentity !== value) {
        await repo.updatePerson(tx, personId, {
          protectedIdentity: value,
          ...(value ? { address: null } : {}),
        });
        await audit.record(tx, {
          action: "person.protection.changed",
          resourceType: "person",
          resourceId: personId,
          changedFields:
            value && current.address ? ["protected_identity", "address"] : ["protected_identity"],
        });
        await outbox.publish(tx, "person.protection.changed", { personId });
      }
      return this.getPersonInTx(tx, personId);
    });
  }

  private async sealPersonalIdentityNumber(
    tx: Tx,
    personId: string,
    input: { country: string; value: string },
    birthDate: string | null,
  ): Promise<{ personalIdentityNumber: string; personalIdentityNumberHash: string }> {
    if (!isSupportedCountry(input.country))
      throw new DomainError("invalid_personal_identity_number");
    const parsed = getCountryPack(input.country).personalIdFormat.parse(input.value);
    if (!parsed) throw new DomainError("invalid_personal_identity_number");
    if (parsed.birthDate !== birthDate) throw new DomainError("personal_identity_number_mismatch");
    const value = `${input.country}:${parsed.normalized}`;
    return {
      personalIdentityNumber: await this.encryption.encrypt(tx, null, value, pinAad(personId)),
      personalIdentityNumberHash: this.encryption.blindIndex(PIN_PURPOSE, value),
    };
  }
}
