// People (docs/domain-model.md): a person exists once in the system and has no
// email. Personal identity numbers are stored encrypted with a blind index for
// duplicate matching; protected persons never have an address stored.

import { getCountryPack, isSupportedCountry } from "@clubadmin/country-packs";
import { audit, type Database, outbox, type TenantContext, type Tx } from "@clubadmin/db";
import {
  type CreatePersonInput,
  CreatePersonSchema,
  type ProfileViewSurface,
  type SignUpPersonInput,
  SignUpPersonSchema,
  type UpdatePersonInput,
  UpdatePersonSchema,
  uuidv7,
} from "@clubadmin/shared";

import type { FieldEncryption } from "../../platform/crypto/field-encryption.ts";
import { DomainError } from "../../platform/domain/domain-error.ts";
import {
  actorPersonId,
  type Context,
  definedOnly,
  parseInput,
  runAs,
} from "../../platform/domain/run.ts";
import * as repo from "./people.repository.ts";

export interface Person {
  id: string;
  givenName: string;
  familyName: string;
  birthDate: string | null;
  gender: string | null;
  protectedIdentity: boolean;
  /** When the global flag was turned on (P1.12). */
  protectedIdentitySetAt: Date | null;
  phone: string | null;
  address: repo.PersonRow["address"];
  hasPersonalIdentityNumber: boolean;
  deceasedAt: Date | null;
  anonymizedAt: Date | null;
  mergedIntoPersonId: string | null;
  createdByPersonId: string | null;
}

const PIN_PURPOSE = "personal_identity_number";
const pinAad = (personId: string) => `people.personal_identity_number:${personId}`;

function toPerson(row: repo.PersonRow): Person {
  return {
    id: row.id,
    givenName: row.givenName,
    familyName: row.familyName,
    birthDate: row.birthDate,
    gender: row.gender,
    protectedIdentity: row.protectedIdentity,
    protectedIdentitySetAt: row.protectedIdentitySetAt,
    phone: row.phone,
    address: row.address,
    hasPersonalIdentityNumber: row.personalIdentityNumber !== null,
    deceasedAt: row.deceasedAt,
    anonymizedAt: row.anonymizedAt,
    mergedIntoPersonId: row.mergedIntoPersonId,
    createdByPersonId: row.createdByPersonId,
  };
}

export class PeopleService {
  private readonly db: Database;
  private readonly encryption: FieldEncryption;

  constructor(db: Database, encryption: FieldEncryption) {
    this.db = db;
    this.encryption = encryption;
  }

  /**
   * Sign-up: creates the acting person's own row (context.personId is the new
   * person's ID, generated by the sign-up flow). The account follows with
   * AccountsService.createAccount.
   */
  createSelf(context: Context, input: SignUpPersonInput): Promise<Person> {
    return runAs(this.db, context, (tx) => this.createSelfInTx(tx, context, input));
  }

  createSelfInTx(tx: Tx, context: Context, input: SignUpPersonInput): Promise<Person> {
    return this.createPersonInTx(tx, context, input, {
      id: actorPersonId(context),
      schema: SignUpPersonSchema,
    });
  }

  /** Creates a person without email (children, people added by a club). `id`: fixed (demo seed). */
  createPerson(
    context: Context,
    input: CreatePersonInput,
    options: { id?: string } = {},
  ): Promise<Person> {
    return runAs(this.db, context, (tx) =>
      this.createPersonInTx(tx, context, input, options.id ? { id: options.id } : {}),
    );
  }

  async createPersonInTx(
    tx: Tx,
    context: Context,
    input: CreatePersonInput | SignUpPersonInput,
    options: { id?: string; schema?: typeof SignUpPersonSchema } = {},
  ): Promise<Person> {
    const data = parseInput(options.schema ?? CreatePersonSchema, input);
    if (data.protectedIdentity && data.address) throw new DomainError("protected_address");
    const id = options.id ?? uuidv7();
    const pin = data.personalIdentityNumber
      ? await this.sealPersonalIdentityNumber(
          tx,
          id,
          data.personalIdentityNumber,
          data.birthDate ?? null,
        )
      : { personalIdentityNumber: null, personalIdentityNumberHash: null };
    const row = await repo.insertPerson(tx, {
      id,
      givenName: data.givenName,
      familyName: data.familyName,
      birthDate: data.birthDate ?? null,
      gender: data.gender ?? null,
      phone: data.phone ?? null,
      address: data.address ?? null,
      protectedIdentity: data.protectedIdentity,
      // Created protected (P1.12: "Add child" with protection, the import):
      // whoever created the person set it.
      ...(data.protectedIdentity
        ? {
            protectedIdentitySetByPersonId: context.personId ?? null,
            protectedIdentitySetAt: new Date(),
          }
        : {}),
      ...pin,
      // Self sign-up creates the actor's own person; otherwise the actor created it.
      createdByPersonId: context.personId && context.personId !== id ? context.personId : null,
    });
    await audit.record(tx, {
      action: "person.created",
      resourceType: "person",
      resourceId: id,
      changedFields: Object.keys(data).filter((k) => data[k as keyof typeof data] != null),
    });
    return toPerson(row);
  }

  getPerson(context: Context, personId: string): Promise<Person> {
    return runAs(this.db, context, (tx) => this.getPersonInTx(tx, personId));
  }

  async getPersonInTx(tx: Tx, personId: string): Promise<Person> {
    const row = await repo.findPerson(tx, personId);
    if (!row) throw new DomainError("not_found");
    return toPerson(row);
  }

  /** People by ID, as visible to the transaction (rows the actor may not reach are missing). */
  getPeople(context: Context, personIds: readonly string[]): Promise<Person[]> {
    return runAs(this.db, context, async (tx) =>
      (await repo.findPeople(tx, personIds)).map(toPerson),
    );
  }

  /** Birth dates by person (grant rules count ages; P1.5). Never serialised. */
  async birthDatesInTx(tx: Tx, personIds: readonly string[]): Promise<Map<string, string | null>> {
    const rows = await repo.findPeople(tx, [...new Set(personIds)]);
    return new Map(rows.map((r) => [r.id, r.birthDate]));
  }

  /**
   * Names and global protected flags for the person presenter, in the order
   * asked (missing rows left out). Never serialise these yourself: pass them
   * to PersonPresenter (ADR 0022).
   */
  summaries(context: Context, personIds: readonly string[]): Promise<repo.PersonSummaryRow[]> {
    return runAs(this.db, context, async (tx) => {
      const rows = new Map((await repo.findSummaries(tx, personIds)).map((r) => [r.id, r]));
      return personIds.flatMap((id) => {
        const row = rows.get(id);
        return row ? [row] : [];
      });
    });
  }

  /**
   * Names of people who asked an operator to create a club (no club yet, so
   * no club access path): read without an actor for the operators' queue.
   */
  requesterSummaries(personIds: readonly string[]): Promise<repo.PersonSummaryRow[]> {
    return this.db.withSystem("ops:club-creation-requests", {}, (tx) =>
      repo.findSummaries(tx, personIds),
    );
  }

  /**
   * The ward and the inviter of a valid guardian invitation, for its landing
   * page (the holder of the link is not related to them yet). Pass the rows
   * to the family presenter, which leaves out protected people.
   */
  invitationPeople(personIds: readonly string[]): Promise<repo.PersonSummaryRow[]> {
    return this.db.withSystem("guardianships:invitation_lookup", {}, (tx) =>
      repo.findSummaries(tx, personIds),
    );
  }

  /**
   * Names and birth dates of duplicate candidates found by
   * app.family_duplicate_candidates (person-merge module), read without an
   * actor: a co-guardian's ward is not reachable by the guardian. Only for
   * those IDs; pass the rows to PersonPresenter.
   */
  duplicateCandidatePeople(
    job: string,
    personIds: readonly string[],
  ): Promise<(repo.PersonSummaryRow & { birthDate: string | null })[]> {
    return this.db.withSystem(job, {}, (tx) => repo.findDuplicatePeople(tx, personIds));
  }

  /** Pairs of the club's members that look like the same person (keyset-paged). */
  clubDuplicates(
    context: TenantContext,
    options: { after: [string, string] | null; limit: number },
  ): Promise<repo.DuplicatePair[]> {
    return this.db.withTenant(context, (tx) => repo.clubDuplicates(tx, context.clubId, options));
  }

  /**
   * The profile view log (P1.12, ADR 0022): someone other than the person
   * opened the profile (or its history). Logged when the person is protected,
   * or in a club that logs every view; one upsert per club, viewer, person
   * and day. Returns whether views of this profile are logged.
   */
  recordProfileView(
    context: Context,
    personId: string,
    view: { clubId: string | null; surface: ProfileViewSurface; protected: boolean },
  ): Promise<boolean> {
    return runAs(this.db, context, (tx) =>
      repo.recordProfileView(tx, personId, view.clubId, view.surface, view.protected),
    );
  }

  /**
   * People named in a club's history and audit log (actors, subjects and
   * person columns), read without an actor: former members, erased people
   * and guardians are no longer reachable through the club, but their
   * actions are the club's own records (ADR 0042). Only for those IDs, for
   * club managers and registrars; pass the rows to PersonPresenter. Erased
   * people (anonymized_at) are flagged so the caller shows "Deleted user".
   */
  historyPeople(
    personIds: readonly string[],
  ): Promise<(repo.PersonSummaryRow & { erased: boolean })[]> {
    return this.db.withSystem("audit:history-people", {}, (tx) =>
      repo.findHistoryPeople(tx, personIds),
    );
  }

  /**
   * Members and senders of a chat (P2.1), read without the viewer's person
   * policy: everyone in a chat sees who else is in it (ADR 0047), and former
   * members stay its authors. Only for IDs of a chat the caller may read; pass
   * the rows to PersonPresenter (protected identity) and show erased people
   * as former members.
   */
  chatPeople(
    personIds: readonly string[],
  ): Promise<(repo.PersonSummaryRow & { erased: boolean })[]> {
    return this.db.withSystem("chat:people", {}, (tx) => repo.findHistoryPeople(tx, personIds));
  }

  /** People by ID without an actor (DEV_AUTH persona picker only). */
  listForDevelopment(personIds: readonly string[]): Promise<Person[]> {
    return this.db.withSystem("dev:personas", {}, async (tx) =>
      (await repo.findPeople(tx, personIds)).map(toPerson),
    );
  }

  /** Marks a person as merged into another (or clears it on undo); person-merge module. */
  async setMergedIntoInTx(tx: Tx, personId: string, into: string | null): Promise<void> {
    await repo.updatePerson(tx, personId, { mergedIntoPersonId: into });
  }

  /** Decrypts the personal identity number (audited). Authorization comes with P0.7. */
  revealPersonalIdentityNumber(
    context: Context,
    personId: string,
  ): Promise<{ country: string; value: string } | null> {
    return runAs(this.db, context, async (tx) => {
      const row = await repo.findPerson(tx, personId);
      if (!row) throw new DomainError("not_found");
      if (!row.personalIdentityNumber) return null;
      await audit.record(tx, {
        action: "person.personal_identity_number.viewed",
        resourceType: "person",
        resourceId: personId,
      });
      const plain = await this.encryption.decrypt(tx, row.personalIdentityNumber, pinAad(personId));
      const separator = plain.indexOf(":");
      return { country: plain.slice(0, separator), value: plain.slice(separator + 1) };
    });
  }

  /**
   * The person's own personal identity number for their "download my data"
   * file (P1.8b; the export job runs as the system). Null when none is stored.
   */
  async personalIdentityNumberInTx(
    tx: Tx,
    personId: string,
  ): Promise<{ country: string; value: string } | null> {
    const row = await repo.findPerson(tx, personId);
    if (!row?.personalIdentityNumber) return null;
    const plain = await this.encryption.decrypt(tx, row.personalIdentityNumber, pinAad(personId));
    const separator = plain.indexOf(":");
    return { country: plain.slice(0, separator), value: plain.slice(separator + 1) };
  }

  /**
   * The club's people (also former members) matching people of a file
   * (adding and importing members, P1.3b): never anyone outside the club.
   */
  clubMatchesInTx(
    tx: Tx,
    clubId: string,
    candidates: readonly repo.ClubMatchCandidate[],
  ): Promise<repo.ClubMatch[]> {
    return repo.clubMatches(tx, clubId, candidates);
  }

  /** The club's people with exactly these names and phone (guardians already in the club). */
  clubPeopleByNameAndPhoneInTx(
    tx: Tx,
    clubId: string,
    candidates: readonly { key: number; given: string; family: string; phone: string }[],
  ): Promise<{ key: number; personId: string }[]> {
    return repo.clubPeopleByNameAndPhone(tx, clubId, candidates);
  }

  /**
   * Parses a personal identity number for a file row (P1.3b): the
   * normalised value with its birth date and blind index, or null if it is
   * invalid for the country.
   */
  parsePersonalIdentityNumber(
    country: string,
    value: string,
  ): { normalized: string; birthDate: string; hash: string } | null {
    if (!isSupportedCountry(country)) return null;
    const parsed = getCountryPack(country).personalIdFormat.parse(value);
    if (!parsed) return null;
    const sealed = `${country}:${parsed.normalized}`;
    return {
      normalized: parsed.normalized,
      birthDate: parsed.birthDate,
      hash: this.encryption.blindIndex(PIN_PURPOSE, sealed),
    };
  }

  /**
   * Creates a person from a file row or the "Add member" form (P1.3b):
   * plain name parts, so callers outside this module never build name
   * fields (ADR 0022).
   */
  createFromIntakeInTx(
    tx: Tx,
    context: Context,
    input: Omit<CreatePersonInput, "givenName" | "familyName">,
    names: { given: string; family: string },
    /** A fixed ID (the demo seed). */
    id?: string,
  ): Promise<Person> {
    return this.createPersonInTx(
      tx,
      context,
      { ...input, givenName: names.given, familyName: names.family },
      id ? { id } : {},
    );
  }

  /** The blind index used to find people with the same personal identity number. */
  personalIdentityNumberHash(country: string, value: string): string | null {
    if (!isSupportedCountry(country)) return null;
    const normalized = getCountryPack(country).personalIdFormat.normalize(value);
    return normalized ? this.encryption.blindIndex(PIN_PURPOSE, `${country}:${normalized}`) : null;
  }

  updateProfile(context: Context, personId: string, patch: UpdatePersonInput): Promise<Person> {
    return runAs(this.db, context, async (tx) => {
      const data = parseInput(UpdatePersonSchema, patch);
      const current = await repo.lockPerson(tx, personId);
      if (!current) throw new DomainError("not_found");
      if (current.protectedIdentity && data.address) throw new DomainError("protected_address");

      const { personalIdentityNumber, ...plain } = data;
      const values: Partial<repo.NewPersonRow> = definedOnly(plain);
      if (personalIdentityNumber !== undefined) {
        Object.assign(
          values,
          personalIdentityNumber
            ? await this.sealPersonalIdentityNumber(
                tx,
                personId,
                personalIdentityNumber,
                data.birthDate ?? current.birthDate,
              )
            : { personalIdentityNumber: null, personalIdentityNumberHash: null },
        );
      }
      const changed = Object.keys(data);
      if (changed.length > 0) {
        await repo.updatePerson(tx, personId, values);
        await audit.record(tx, {
          action: "person.updated",
          resourceType: "person",
          resourceId: personId,
          changedFields: changed,
        });
      }
      return this.getPersonInTx(tx, personId);
    });
  }

  /**
   * Sets or clears the global protected identity flag (ADR 0022, P1.12). Only
   * the person themselves or a full guardian may change it. Turning it on
   * removes the stored address and records who did it. Turning a ward's flag
   * off is refused (audited, `protection_removal_not_allowed`) unless the
   * caller set it or whoever set it is no longer a full guardian; the person
   * may remove their own flag only when `selfMayRemove` (consent age, the
   * caller checks it).
   */
  async setProtectedIdentity(
    context: Context,
    personId: string,
    value: boolean,
    options: { selfMayRemove?: boolean } = {},
  ): Promise<Person> {
    const result = await runAs(this.db, context, async (tx) => {
      const actor = actorPersonId(context);
      const current = await repo.lockPerson(tx, personId);
      if (!current) throw new DomainError("not_found");
      if (actor !== personId && !(await repo.actorIsFullGuardianOf(tx, personId))) {
        throw new DomainError("not_a_full_guardian");
      }
      if (current.protectedIdentity === value) return { refused: false };
      if (!value) {
        const allowed =
          actor === personId
            ? options.selfMayRemove !== false
            : current.protectedIdentitySetByPersonId === null ||
              current.protectedIdentitySetByPersonId === actor ||
              !(await repo.isActiveFullGuardian(
                tx,
                current.protectedIdentitySetByPersonId,
                personId,
              ));
        if (!allowed) {
          await audit.record(tx, {
            action: "person.protection.removal_refused",
            resourceType: "person",
            resourceId: personId,
          });
          return { refused: true };
        }
      }
      await repo.updatePerson(tx, personId, {
        protectedIdentity: value,
        protectedIdentitySetByPersonId: value ? actor : null,
        protectedIdentitySetAt: value ? new Date() : null,
        ...(value ? { address: null } : {}),
      });
      await audit.record(tx, {
        action: "person.protection.changed",
        resourceType: "person",
        resourceId: personId,
        changedFields:
          value && current.address ? ["protected_identity", "address"] : ["protected_identity"],
      });
      await outbox.publish(tx, "person.protection.changed", {
        personId,
        enabled: value,
        scope: "global",
        ...(actor ? { byPersonId: actor } : {}),
      });
      return { refused: false };
    });
    // The refusal is audited in its own committed transaction above.
    if (result.refused) throw new DomainError("protection_removal_not_allowed");
    return this.getPerson(context, personId);
  }

  private async sealPersonalIdentityNumber(
    tx: Tx,
    personId: string,
    input: { country: string; value: string },
    birthDate: string | null,
  ): Promise<{ personalIdentityNumber: string; personalIdentityNumberHash: string }> {
    if (!isSupportedCountry(input.country))
      throw new DomainError("invalid_personal_identity_number");
    const parsed = getCountryPack(input.country).personalIdFormat.parse(input.value);
    if (!parsed) throw new DomainError("invalid_personal_identity_number");
    if (parsed.birthDate !== birthDate) throw new DomainError("personal_identity_number_mismatch");
    const value = `${input.country}:${parsed.normalized}`;
    return {
      personalIdentityNumber: await this.encryption.encrypt(tx, null, value, pinAad(personId)),
      personalIdentityNumberHash: this.encryption.blindIndex(PIN_PURPOSE, value),
    };
  }
}
