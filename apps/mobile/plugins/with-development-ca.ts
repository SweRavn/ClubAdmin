// Config plugin: development-variant builds trust Caddy's local CA for
// https://*.clubadmin.localhost (docs/development.md, "Mobile"). It is only
// added for APP_VARIANT=development (app.config.ts): preview and production
// builds trust the system store only. The development variant has its own
// app ID and is never published; CI runs its release build (JavaScript
// bundled, no Metro) against the local services. The certificate comes from
// .local/caddy-root.crt (written by `pnpm dev:services`); without it the
// build trusts the user CA store (pnpm dev:trust-ca --android) as well.

import { copyFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import {
  AndroidConfig,
  type ConfigPlugin,
  withAndroidManifest,
  withDangerousMod,
} from "expo/config-plugins";

const CA_RESOURCE = "clubadmin_dev_ca";
const CONFIG_RESOURCE = "clubadmin_network_security";

export function networkSecurityConfig(withCaResource: boolean): string {
  const ca = withCaResource ? `\n      <certificates src="@raw/${CA_RESOURCE}" />` : "";
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-development-ca.ts for development-variant builds only. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="false">
    <trust-anchors>
      <certificates src="system" />${ca}
      <certificates src="user" />
    </trust-anchors>
  </base-config>
</network-security-config>
`;
}

const withDevelopmentCa: ConfigPlugin<{ enabled: boolean }> = (config, { enabled }) => {
  if (!enabled) return config;
  config = withDangerousMod(config, [
    "android",
    (mod) => {
      const res = join(mod.modRequest.platformProjectRoot, "app", "src", "main", "res");
      const caFile = join(mod.modRequest.projectRoot, "..", "..", ".local", "caddy-root.crt");
      const hasCa = existsSync(caFile);
      if (hasCa) {
        mkdirSync(join(res, "raw"), { recursive: true });
        copyFileSync(caFile, join(res, "raw", `${CA_RESOURCE}.pem`));
      } else {
        console.warn(
          "with-development-ca: .local/caddy-root.crt not found (run `pnpm dev:services`); " +
            "the development build trusts the user CA store only.",
        );
      }
      mkdirSync(join(res, "xml"), { recursive: true });
      writeFileSync(join(res, "xml", `${CONFIG_RESOURCE}.xml`), networkSecurityConfig(hasCa));
      return mod;
    },
  ]);
  return withAndroidManifest(config, (mod) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(mod.modResults);
    application.$["android:networkSecurityConfig"] = `@xml/${CONFIG_RESOURCE}`;
    return mod;
  });
};

export default withDevelopmentCa;
