// docs/roles-and-permissions.md (P2.7b): the permission catalogue and the
// built-in template's roles, generated from the code so that the document
// never drifts (a unit test compares it). Run `pnpm docs:roles` after
// changing the catalogue, the template or their texts.

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import { type Locale, translate } from "@clubadmin/i18n";
import {
  BUILT_IN_ROLE_TEMPLATE,
  CLUB_ROLES,
  GROUP_FUNCTIONS,
  PERMISSION_AREAS,
  PERMISSION_CATALOGUE,
  type RolePermission,
} from "@clubadmin/shared";

export const ROLES_DOC_PATH = join(
  fileURLToPath(new URL(".", import.meta.url)),
  "../../../docs/roles-and-permissions.md",
);

const text = (locale: Locale, key: string) => translate(locale, key as never);
const keyOf = (permission: string) => permission.replaceAll(".", "_");
const cell = (value: string) => value.replaceAll("|", "\\|").replaceAll("\n", " ");

export function rolesDoc(): string {
  const rolePermissions = (
    Object.entries(PERMISSION_CATALOGUE) as [
      RolePermission,
      (typeof PERMISSION_CATALOGUE)[RolePermission],
    ][]
  )
    .filter(([, entry]) => entry.kind === "role")
    .map(([permission, entry]) => ({
      permission,
      entry: entry as Extract<typeof entry, { kind: "role" }>,
    }));
  const permissionName = (locale: Locale, p: string) =>
    text(locale, `permissionCatalogue.permissions.${keyOf(p)}.name`);
  const lines: string[] = [];
  const out = (line = "") => lines.push(line);
  out("# Roles and permissions");
  out();
  out(
    "<!-- Generated by `pnpm docs:roles` from packages/shared/src/authorization/permission-catalogue.ts",
  );
  out("     and the message catalogues; do not edit by hand (a unit test compares it). -->");
  out();
  out("What a person may do in a club comes only from **permissions** held through");
  out("**roles** (ADR 0046). A **club role** (administrator, registrar, treasurer, …)");
  out("applies in the whole club; a **group role** (in older text a *function*:");
  out("player, head coach, team manager, …) applies in its group. Each club starts");
  out("with the built-in template below and can change the roles' permissions and");
  out("create its own roles (named at least in the club's language and English).");
  out("A participant of a group is someone whose group role holds");
  out("`group.participate`; a leader one whose role holds `group.lead`.");
  out();
  out("Role keys that still decide something, on purpose: the locked");
  out("`club_manager` (the last administrator cannot leave or be removed, the");
  out('club\'s creator gets it, the invitation preset "administrator"; ADR 0018,');
  out("ADR 0046 A3) and the locked `chair` (recovering a club without");
  out("administrators). Everywhere else a role key is only a label");
  out("(`clubadmin/no-role-names`). The club page's administrator list is");
  out("[#25](https://github.com/SweRavn/ClubAdmin/issues/25).");
  out();
  out("## The built-in template's roles");
  out();
  for (const [title, keys, enumName] of [
    ["Club roles", CLUB_ROLES, "roles"],
    ["Group roles", GROUP_FUNCTIONS, "functions"],
  ] as const) {
    out(`### ${title}`);
    out();
    out("| Role (sv / en) | Key | Permissions |");
    out("|---|---|---|");
    for (const key of keys) {
      const role = BUILT_IN_ROLE_TEMPLATE[key];
      const names = `${text("sv", `${enumName}.${key}`)} / ${text("en", `${enumName}.${key}`)}`;
      const permissions = [...role.permissions]
        .sort()
        .map((p) => `\`${p}\``)
        .join(", ");
      out(`| ${cell(names)} | \`${key}\` | ${permissions || "–"} |`);
    }
    out();
  }
  out("## Permissions by area");
  out();
  out("Scope: where the permission applies. Sensitive: access to many people's");
  out("personal data, protected identity, money, history or roles (the roles page");
  out("warns before giving it).");
  out();
  for (const area of PERMISSION_AREAS) {
    const inArea = rolePermissions
      .filter((r) => r.entry.area === area)
      .sort((a, b) => a.permission.localeCompare(b.permission));
    if (inArea.length === 0) continue;
    out(
      `### ${text("en", `permissionCatalogue.areas.${area}`)} (${text("sv", `permissionCatalogue.areas.${area}`)})`,
    );
    out();
    out("| Permission | Scope | Sensitive | Svenska | English |");
    out("|---|---|---|---|---|");
    for (const { permission, entry } of inArea) {
      const sv = `**${permissionName("sv", permission)}**: ${text("sv", `permissionCatalogue.permissions.${keyOf(permission)}.description`)}`;
      const en = `**${permissionName("en", permission)}**: ${text("en", `permissionCatalogue.permissions.${keyOf(permission)}.description`)}`;
      out(
        `| \`${permission}\` | ${entry.scope} | ${entry.sensitive ? "yes" : ""} | ${cell(sv)} | ${cell(en)} |`,
      );
    }
    out();
  }
  return `${lines.join("\n")}`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(ROLES_DOC_PATH, rolesDoc());
  console.log(`wrote ${ROLES_DOC_PATH}`);
}
