ALTER TABLE public.accounts ADD COLUMN pending_email_expires_at timestamptz;
ALTER TABLE public.accounts ADD COLUMN pending_email_attempts smallint NOT NULL DEFAULT 0;
ALTER TABLE public.accounts ADD CONSTRAINT accounts_pending_email_complete CHECK (
