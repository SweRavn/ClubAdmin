-- member's phone and address (club.people.contact.edit); the template of
-- 0053 with these rows, given to the clubs' roles of those templates.
--
-- Changing one's login email: the new address waits in pending_email until
-- the code sent to it is entered. The code is derived from
-- pending_email_id with INVITATION_TOKEN_KEY (the worker emails it), so it
-- is stored nowhere; pending_email_attempts counts wrong codes. The old
-- address is told from the account's history (account.email.changed).

